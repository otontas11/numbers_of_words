const fs = require('fs');
const path = require('path');
const {
  withAppBuildGradle,
  withDangerousMod,
  withMainApplication,
} = require('@expo/config-plugins');

const MODULE_NAME = 'AndroidGameSoundPoolModule.kt';
const PACKAGE_REGISTRATION = '          add(AndroidGameSoundPoolPackage())';
const GRADLE_BLOCK_START = '/* @generated by with-android-game-sound-pool: begin */';
const GRADLE_BLOCK_END = '/* @generated by with-android-game-sound-pool: end */';

const SOUND_FILES = [
  'select.wav',
  'select-2.wav',
  'select-3.wav',
  'select-4.wav',
  'select-5.wav',
  'select-6.wav',
  'select-7.wav',
  'hint.wav',
  'success.wav',
  'bonus.wav',
  'dimaond.mp3',
  'game-treasure.wav',
  'points.wav',
  'shuffle.wav',
];

function createGradleBlock() {
  const soundNames = SOUND_FILES.map((fileName) => `    "${fileName}",`).join('\n');
  return `${GRADLE_BLOCK_START}
def gameSoundSourceDir = file("\${projectRoot}/assets/sounds")
def gameSoundAssetNames = [
${soundNames}
]
def generatedGameSoundAssetsDir = layout.buildDirectory.dir("generated/game-sound-assets")
def generateGameSoundAssets = tasks.register("generateGameSoundAssets", Sync) {
    group = "build"
    description = "Stages the allowlisted game sounds as Android assets."
    duplicatesStrategy = DuplicatesStrategy.FAIL
    includeEmptyDirs = false

    gameSoundAssetNames.each { soundFileName ->
        from(new File(gameSoundSourceDir, soundFileName)) {
            into("sounds")
        }
    }
    into(generatedGameSoundAssetsDir)

    doFirst {
        def missingSounds = gameSoundAssetNames.findAll {
            !new File(gameSoundSourceDir, it).isFile()
        }
        if (!missingSounds.isEmpty()) {
            throw new GradleException("Missing required game sounds: \${missingSounds.join(', ')}")
        }
    }
}

android {
    androidResources {
        noCompress += ['wav', 'mp3']
    }
    sourceSets {
        main {
            assets.srcDir(generatedGameSoundAssetsDir)
        }
    }
}

tasks.named("preBuild").configure {
    dependsOn(generateGameSoundAssets)
}
${GRADLE_BLOCK_END}`;
}

function addPackageRegistration(contents) {
  if (contents.includes('add(AndroidGameSoundPoolPackage())')) return contents;

  const packageListStart = /(PackageList\(this\)\.packages\.apply\s*\{\s*\n)/;
  if (!packageListStart.test(contents)) {
    throw new Error('Unable to find the React Native package list in MainApplication.');
  }
  return contents.replace(packageListStart, `$1${PACKAGE_REGISTRATION}\n`);
}

function addGeneratedSoundAssets(contents) {
  const block = createGradleBlock();
  const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const generatedBlockPattern = new RegExp(
    `${escapeRegExp(GRADLE_BLOCK_START)}[\\s\\S]*?${escapeRegExp(GRADLE_BLOCK_END)}`,
  );

  if (generatedBlockPattern.test(contents)) {
    return contents.replace(generatedBlockPattern, block);
  }
  // Preserve an already-patched native tree without adding a duplicate task.
  if (contents.includes('tasks.register("generateGameSoundAssets"')) return contents;
  if (!contents.includes('dependencies {')) {
    throw new Error('Unable to find dependencies block in android/app/build.gradle.');
  }
  return contents.replace('dependencies {', `${block}\n\ndependencies {`);
}

function withNativeSource(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const androidPackage = modConfig.android?.package;
      if (!androidPackage) {
        throw new Error('android.package is required for AndroidGameSoundPool.');
      }

      const templatePath = path.join(
        modConfig.modRequest.projectRoot,
        'plugins',
        'android-game-sound-pool',
        MODULE_NAME,
      );
      const javaDirectory = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'java',
        ...androidPackage.split('.'),
      );
      const template = await fs.promises.readFile(templatePath, 'utf8');
      if (!template.includes('__ANDROID_PACKAGE__')) {
        throw new Error(`Missing __ANDROID_PACKAGE__ token in ${templatePath}`);
      }

      await fs.promises.mkdir(javaDirectory, { recursive: true });
      await fs.promises.writeFile(
        path.join(javaDirectory, MODULE_NAME),
        template.replaceAll('__ANDROID_PACKAGE__', androidPackage),
      );
      // Older iterations used a second source file. The package now lives in the
      // generated module file, so remove that stale file on non-clean prebuilds.
      await fs.promises.rm(path.join(javaDirectory, 'AndroidGameSoundPoolPackage.kt'), {
        force: true,
      });
      return modConfig;
    },
  ]);
}

function withPackageRegistration(config) {
  return withMainApplication(config, (modConfig) => {
    modConfig.modResults.contents = addPackageRegistration(modConfig.modResults.contents);
    return modConfig;
  });
}

function withGeneratedSoundAssets(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== 'groovy') {
      throw new Error('AndroidGameSoundPool currently requires app/build.gradle (Groovy).');
    }

    modConfig.modResults.contents = addGeneratedSoundAssets(modConfig.modResults.contents);
    return modConfig;
  });
}

module.exports = function withAndroidGameSoundPool(config) {
  config = withNativeSource(config);
  config = withPackageRegistration(config);
  config = withGeneratedSoundAssets(config);
  return config;
};

module.exports._internal = {
  addGeneratedSoundAssets,
  addPackageRegistration,
  createGradleBlock,
};
